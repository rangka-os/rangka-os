#!/usr/bin/env python3
"""Bundle apps/*/app.rk + models/*.rk + fixtures into the prototype's meta.js. The prototype reads nothing else."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rkfile import load, find, listdir
root, out = sys.argv[1], sys.argv[2]
order = ["crm", "sales", "core"]
menu, models, sources, dashboards, dash_list = [], {}, {}, {}, []
for app in order:
    d = os.path.join(root, "apps", app)
    man = load(find(d, "app"))[0]
    menu += [{**g, "app": app} for g in man.get("menu", [])]
    for dn in man.get("dashboards", []):
        dp = find(os.path.join(d, "dashboards"), dn)
        db = load(dp)[0]; db.pop("$schema", None); dashboards[dn] = db
        dash_list.append({"name": dn, "app": app, "label": db["label"]})
        sources["dashboard:" + dn] = {"path": os.path.relpath(dp, root), "text": open(dp, encoding="utf-8").read()}
    for _, p in listdir(os.path.join(d, "models")):
        m = load(p)[0]; m.pop("$schema", None); models[m["name"]] = m
        sources[m["name"]] = {"path": os.path.relpath(p, root), "text": open(p, encoding="utf-8").read()}
seed = {}
for fx in ("demo", "crm_demo"):
    seed.update(load(find(os.path.join(root, "fixtures"), fx))[0])
meta = {"app": {"name": "kopi-senja", "title": {"id": "Kopi Senja", "en": "Kopi Senja"}, "installed": order, "menu": menu, "dashboards": dash_list}, "models": models, "dashboards": dashboards, "sources": sources}
open(out, "w").write("/* Generated by tools/build_proto.py from apps/{" + ",".join(order) + "}. Do not edit by hand. */\nwindow.RANGKA_META = " + json.dumps(meta, ensure_ascii=False, indent=1) + ";\nwindow.RANGKA_SEED = " + json.dumps(seed, ensure_ascii=False, indent=1) + ";\n")
print(out, len(models), "models")
